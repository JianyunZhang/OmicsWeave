def get_hmdb_id(metabolite_name: str) -> Optional[str]:
    """返回代谢物的 HMDB ID，未找到返回 None。"""
    result = lookup_metabolite_ids(metabolite_name)
    return result['hmdb_id'] if result else None


def get_kegg_compound(metabolite_name: str) -> Optional[str]:
    """返回代谢物的 KEGG Compound ID，未找到返回 None。"""
    result = lookup_metabolite_ids(metabolite_name)
    return result['kegg_compound'] if result else None


def get_chebi_id(metabolite_name: str) -> Optional[str]:
    """返回代谢物的 ChEBI ID，未找到返回 None。"""
    result = lookup_metabolite_ids(metabolite_name)
    return result['chebi_id'] if result else None
