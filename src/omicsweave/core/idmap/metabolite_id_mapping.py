# 预建一个查找索引：规范化名称 -> 原始键
_NORMALIZED_INDEX: dict[str, str] | None = None
# 用于去除常见前缀的模式
_STRIP_PREFIX_RE = re.compile(r'^[DLdl]-|^DL-|^\-')

def _normalize_name(name: str) -> str:
    """将代谢物名称规范化为统一格式，用于模糊匹配。"""
    if not isinstance(name, str):
        return ""
    s = name.strip()
    s = _STRIP_PREFIX_RE.sub('', s)
    s = s.lower()
    s = s.replace('  ', ' ').replace('\t', ' ')
    s = re.sub(r'[\-\–]', '-', s)  # 统一连字符
    s = re.sub(r'[,\;]', '', s)     # 去除逗号分号
    return s


def _build_index() -> dict[str, str]:
    """构建规范化名称 → 原始键的索引（懒初始化）。"""
    global _NORMALIZED_INDEX
    if _NORMALIZED_INDEX is not None:
        return _NORMALIZED_INDEX
    _NORMALIZED_INDEX = {}
    for key in METABOLITE_DATABASE_IDS:
        norm = _normalize_name(key)
        if norm:
            _NORMALIZED_INDEX[norm] = key
    return _NORMALIZED_INDEX


def lookup_metabolite_ids(
    name: str,
    default: dict[str, Optional[str]] | None = None,
) -> Optional[Dict[str, Optional[str]]]:
    """
    根据代谢物名称查找数据库 ID，支持名称变体模糊匹配。

    匹配策略（按优先级）:
        1. 原始名称精确匹配
        2. 名称 trim 后精确匹配
        3. 去除 L-/D-/DL- 前缀后匹配
        4. 规范化（小写、去连字符）后索引查找

    Parameters
    ----------
    name : str
        代谢物名称（如 "L-Glutamate", "glucose", "Citric acid"）
    default : dict or None
        未匹配时返回的默认值。None 表示返回 None。

    Returns
    -------
    dict or None
        {'hmdb_id': ..., 'kegg_compound': ..., 'chebi_id': ...} 或 default
    """
    if not isinstance(name, str) or not name.strip():
        return default

    s = name.strip()

    # 1. 精确匹配
    if s in METABOLITE_DATABASE_IDS:
        return METABOLITE_DATABASE_IDS[s]

    # 2. 去除 L-/D- 前缀后再精确匹配
    stripped = _STRIP_PREFIX_RE.sub('', s).strip()
    if stripped in METABOLITE_DATABASE_IDS:
        return METABOLITE_DATABASE_IDS[stripped]

    # 3. 规范化后索引查找
    norm = _normalize_name(s)
    if norm:
        idx = _build_index()
        matched_key = idx.get(norm)
        if matched_key:
            return METABOLITE_DATABASE_IDS[matched_key]

    return default


def annotate_metabolites(
    df: pd.DataFrame,
    name_col: str = "Compounds",
    inplace: bool = False,
) -> pd.DataFrame:
    """
    为代谢物 DataFrame 添加 HMDB、KEGG_Compound、ChEBI 注释列。

    Parameters
    ----------
    df : pd.DataFrame
        含化合物名称列的 DataFrame
    name_col : str
        化合物名称列名，默认 "Compounds"
    inplace : bool
        True 时直接修改传入的 DataFrame

    Returns
    -------
    pd.DataFrame
        新增 HMDB / KEGG_Compound / ChEBI 三列
    """
    if not inplace:
        df = df.copy()

    hmdb_list, kegg_list, chebi_list = [], [], []

    for name in df[name_col] if name_col in df.columns else []:
        result = lookup_metabolite_ids(str(name))
        if result is not None:
            hmdb_list.append(result.get("hmdb_id", ""))
            kegg_list.append(result.get("kegg_compound", ""))
            chebi_list.append(result.get("chebi_id", ""))
        else:
            hmdb_list.append("")
            kegg_list.append("")
            chebi_list.append("")

    df["HMDB"] = hmdb_list
    df["KEGG_Compound"] = kegg_list
    df["ChEBI"] = chebi_list

    matched = sum(1 for v in hmdb_list if v or isinstance(v, str) and v)
    print(f"    代谢物 ID 注释: {matched}/{len(hmdb_list)} 个匹配到数据库 ID")

    return df


